pub fn value(c: char) -> Option<u32> {
    let code = c as u32;
    let index = RUNS
        .partition_point(|&(start, _)| start <= code)
        .checked_sub(1)?;
    let (start, length) = RUNS[index];
    (code < start + length).then(|| code - start)
}
